/** markdown 源文本 → 搜索用纯文本。纯逻辑，vitest 直接可测。
 *  串行正则替换，顺序敏感：先剥结构块（frontmatter/代码块）再处理行内语法，
 *  否则代码块里的 [[ ]]、标记符号会被误处理。 */

export function markdownToPlainText(body: string): string {
  return (
    body
      // frontmatter 整块剥掉
      .replace(/^---\r?\n[\s\S]*?\r?\n---\r?\n?/, "")
      // 围栏代码块整块移除（``` 与 ~~~，含语言标注行）；代码内容不进搜索索引
      .replace(/(^|\n)(```|~~~)[^\n]*\n[\s\S]*?\n\2[^\n]*/g, "$1")
      // 图片 → alt 文本
      .replace(/!\[([^\]]*)\]\([^)]*\)/g, "$1")
      // 链接 → 锚文本
      .replace(/\[([^\]]*)\]\([^)]*\)/g, "$1")
      // wikilink → 别名优先的可读文本（[[x|y]] → y，[[x]] → x），embed 前缀一并去掉
      .replace(/!?\[\[([^\[\]]+)\]\]/g, (_m, inner: string) => {
        const sep = inner.indexOf("|");
        return sep >= 0 ? inner.slice(sep + 1) : inner;
      })
      // 行内 code 去反引号保留内容
      .replace(/`([^`]*)`/g, "$1")
      // math：$$ 块先于 $ 行内，去定界符留公式内容
      .replace(/\$\$([\s\S]*?)\$\$/g, "$1")
      .replace(/\$([^$\n]+)\$/g, "$1")
      // 内嵌 HTML 标签剥掉
      .replace(/<[^>]+>/g, "")
      // 表格分隔行（|---|---:）整行清除——须在行首标记剥除之前，
      // 否则分隔行的首个 - 会被当成列表标记吃掉一个字符
      .replace(/^[ \t]*\|?[ \t]*:?-{3,}:?([ \t]*\|[ \t]*:?-{3,}:?)*[ \t]*\|?[ \t]*$/gm, "")
      // 行首标记：标题 #、引用 >、列表 -/*/+/数字.、表格管道
      .replace(/^[ \t]*(#{1,6}|>|[-*+]|\d+\.|\|)[ \t]*/gm, "")
      // 行尾管道（表格行右端）
      .replace(/[ \t]*\|[ \t]*$/gm, "")
      // 强调/删除线标记。只删成对标记语法，单 _ 保留（snake_case 变量名正文可读性）
      .replace(/(\*\*\*|\*\*|\*|___|__|~~)/g, "")
      // 连续空白折叠为单空格
      .replace(/\s+/g, " ")
      .trim()
  );
}
